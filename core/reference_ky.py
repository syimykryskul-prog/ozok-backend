def ky_of(ru, mapping):
    """Перевод по словарю; для брендов и названий без перевода (латиница) — то же значение."""
    return mapping.get(ru, "")


def fill(get_model):
    """Заполняет пустые *_ky по словарям (get_model(app, name) -> модель; apps.get_model в миграции)."""
    for app, model, field, mapping in FIELD_MAP:
        Model = get_model(app, model)
        for ru, ky in mapping.items():
            Model.objects.filter(**{field: ru, f"{field}_ky": ""}).update(**{f"{field}_ky": ky})
    ChecklistTemplate = get_model("clients", "ChecklistTemplate")
    for tpl in ChecklistTemplate.objects.all():
        tpl.items = normalize_items(tpl.items, fill=True)
        tpl.save(update_fields=["items"])
    Implementation = get_model("clients", "Implementation")
    for inst in Implementation.objects.all():
        changed = False
        for row in inst.checklist or []:
            if isinstance(row, dict) and not row.get("item_ky") and row.get("item") in CHECKLIST_ITEM:
                row["item_ky"] = CHECKLIST_ITEM[row["item"]]
                changed = True
        if changed:
            inst.save(update_fields=["checklist"])
    Audit = get_model("quality", "Audit")
    for a in Audit.objects.all():
        changed = False
        for i in a.items:
            if isinstance(i, dict) and not i.get("criterion_ky") and i.get("criterion") in AUDIT_CRITERION:
                i["criterion_ky"] = AUDIT_CRITERION[i["criterion"]]
                changed = True
        if changed:
            a.save(update_fields=["items"])


def normalize_items(items, fill=False):
    """Пункты чек-листа шаблона -> [{"ru": ..., "ky": ...}]; при fill=True пустой ky берётся из словаря."""
    out = []
    for i in items or []:
        if isinstance(i, str):
            ru, ky = i, ""
        else:
            ru, ky = i.get("ru") or i.get("item") or "", i.get("ky") or i.get("item_ky") or ""
        out.append({"ru": ru, "ky": ky or (CHECKLIST_ITEM.get(ru, "") if fill else "")})
    return out
